#!/usr/bin/env bash
# Renders the task's manifest, hotel.yaml, from the repository's k8s/base (the same objects
# scripts/k8s-deploy.sh applies) for vibesys-evaluator's k8s deploy: without the Namespace object
# and the fixed namespace (each sample deploys into a namespace of its own), and with the image
# the task builds from the candidate's Dockerfile, ${HOTEL_IMAGE}.
#
#   .vibesys/tasks/rpc-policy-k8s/k8s/render.sh           # rewrite hotel.yaml
#   .vibesys/tasks/rpc-policy-k8s/k8s/render.sh --check   # fail if hotel.yaml is stale
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../../../.." && pwd)"
rendered="$(
  echo "# Generated by render.sh from k8s/base; do not edit."
  kubectl kustomize --load-restrictor LoadRestrictionsNone "$root/k8s/base" | awk '
    # One document at a time; drop the Namespace, the fixed namespace and image.
    function flush() { if (doc != "" && doc !~ /\nkind: Namespace\n/) printf "%s", doc; doc = "" }
    /^---$/ { flush(); doc = "---\n"; next }
    /^  namespace: rpcstack-hotel$/ { next }
    { sub(/image: localhost:5001\/rpcstack-hotel:baseline$/, "image: ${HOTEL_IMAGE}"); doc = doc $0 "\n" }
    END { flush() }
  '
)"
if grep -q 'rpcstack-hotel:baseline\|namespace: rpcstack-hotel\|kind: Namespace' <<<"$rendered"; then
  echo "render.sh: the rendered manifest still names the fixed image or namespace" >&2
  exit 1
fi
if [ "${1:-}" = "--check" ]; then
  if ! diff -u "$here/hotel.yaml" - <<<"$rendered"; then
    echo "render.sh: hotel.yaml is stale; run $0" >&2
    exit 1
  fi
  exit 0
fi
printf '%s\n' "$rendered" > "$here/hotel.yaml"
